import math
num = int(input("Enter the Number: "))
print("Square root of a Number: ", math.sqrt(num))
angle_deg = float(input("Enter angle in degrees: "))
angle_rad = math.radians(angle_deg)
print("Sine Angle: ", math.sin(angle_rad))
print("Cosine Angle: ", math.cos(angle_rad))
print("Tan Angle: ", math.tan(angle_rad))